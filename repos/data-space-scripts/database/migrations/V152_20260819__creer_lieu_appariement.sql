    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_metabase') THEN
        GRANT SELECT ON dataviz.lieu_appariements_a_valider TO app_metabase;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'nao_ro') THEN
        GRANT SELECT ON main.lieu_appariement TO nao_ro;
    END IF;
END
