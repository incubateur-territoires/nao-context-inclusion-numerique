-- ============================================================
-- V149 – Département de rattachement des EPCI (SEPT #1828)
-- ============================================================
-- admin.epci n'a aucun lien direct vers un département : le seul chemin est
-- commune_epci → commune.departement_id, qui donne plusieurs départements
-- pour les 91 EPCI interdépartementaux (85 sur 2 départements, 5 sur 3,
-- Métropole du Grand Paris sur 6).
--
-- Nouvelle colonne departement_id = département de rattachement OFFICIEL,
-- issu du référentiel Banatic (DGCL) : département de la commune siège du
-- groupement (export prégénéré quotidien
-- https://www.banatic.interieur.gouv.fr/consultation/api/export/pregenere/telecharger/France).
-- Repli pour les EPCI absents de Banatic (millésimes IGN/Banatic décalés,
-- ex. EPCI fusionnés) : département majoritaire en nombre de communes
-- membres, tie-break population puis code département.
--
-- La colonne est NULLABLE : admin.epci est truncatée/reconstruite à chaque
-- run du DAG init_ref_data, la valeur est recalculée par les nouvelles
-- tâches import_banatic_groupement + transfert_epci_departement (après
-- reconstruction de commune_epci). La FK vers admin.departement est sûre :
-- departement n'est jamais truncatée par le DAG (ids stables).

ALTER TABLE admin.epci ADD COLUMN departement_id INTEGER;

ALTER TABLE admin.epci
    ADD CONSTRAINT epci_departement_id FOREIGN KEY (departement_id) REFERENCES admin.departement (id);

CREATE INDEX epci_departement_id_idx ON admin.epci (departement_id);

COMMENT ON COLUMN admin.epci.departement_id IS
    'Département de rattachement officiel (Banatic/DGCL : département de la commune siège) ; repli département majoritaire en nombre de communes membres si absent de Banatic. Recalculé à chaque run du DAG init_ref_data.';

