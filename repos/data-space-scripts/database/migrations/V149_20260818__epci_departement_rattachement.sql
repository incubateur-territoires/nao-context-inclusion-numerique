-- Repli majoritaire pour les EPCI absents du snapshot Banatic.
WITH maj AS (
    SELECT ce.epci_id,
           c.departement_id,
           ROW_NUMBER() OVER (
               PARTITION BY ce.epci_id
               ORDER BY COUNT(*) DESC, SUM(COALESCE(c.population, 0)) DESC, MIN(d.code)
           ) AS rang
    FROM admin.commune_epci AS ce
    INNER JOIN admin.commune AS c ON c.id = ce.commune_id
    INNER JOIN admin.departement AS d ON d.id = c.departement_id
    GROUP BY ce.epci_id, c.departement_id
)
UPDATE admin.epci
SET departement_id = maj.departement_id
FROM maj
WHERE maj.epci_id = epci.id
  AND maj.rang = 1
  AND epci.departement_id IS NULL;
