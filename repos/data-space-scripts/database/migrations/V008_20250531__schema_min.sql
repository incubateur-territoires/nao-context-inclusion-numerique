DO
$do$
BEGIN
   IF EXISTS (
      SELECT FROM pg_catalog.pg_roles
      WHERE  rolname = 'min_scalingo') THEN

      RAISE NOTICE 'Role "min_scalingo" already exists. Skipping.';
   ELSE
      CREATE ROLE min_scalingo LOGIN CREATEDB;
      COMMENT ON ROLE min_scalingo IS 'Rôle applicatif pour MIN depuis Scalingo.';
   END IF;
END
$do$;

GRANT CONNECT ON DATABASE dataspace_test, dataspace_dev, dataspace_prod TO min_scalingo;


-- Usage on schemas
GRANT USAGE ON SCHEMA main, reference, admin, min TO min_scalingo;

-- Create on min dedicated schema
GRANT ALL ON SCHEMA min TO min_scalingo;

-- Select and references (foreign keys) on main, admin and reference tables
GRANT SELECT, REFERENCES ON ALL TABLES IN SCHEMA main, reference, admin TO min_scalingo;
ALTER DEFAULT PRIVILEGES IN SCHEMA main, reference, admin GRANT SELECT ON TABLES TO min_scalingo;

-- Need to read and write structures and adresses
GRANT SELECT, INSERT, UPDATE ON TABLE main.structure, main.adresse TO min_scalingo;
GRANT USAGE ON SEQUENCE main.structure_id_seq, main.adresse_id_seq TO min_scalingo;

-- ALTER DEFAULT PRIVILEGES IN SCHEMA min TO min_scalingo
ALTER DEFAULT PRIVILEGES IN SCHEMA min GRANT ALL ON TABLES TO min_scalingo;
ALTER DEFAULT PRIVILEGES IN SCHEMA min GRANT ALL ON SEQUENCES TO min_scalingo;
GRANT ALL ON ALL TABLES IN SCHEMA min TO min_scalingo;
GRANT ALL ON ALL SEQUENCES IN SCHEMA min TO min_scalingo;


