CREATE TYPE min."Role" AS ENUM (
    'administrateur_dispositif',
    'gestionnaire_departement',
    'gestionnaire_groupement',
    'gestionnaire_region',
    'gestionnaire_structure',
    'instructeur',
    'pilote_politique_publique',
    'support_animation'
);

